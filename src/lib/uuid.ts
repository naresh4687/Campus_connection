/**
 * A random UUID for client-side idempotency keys. crypto.randomUUID() exists only in secure contexts (HTTPS or localhost), so a phone
 * or second PC opening the dev server by its LAN IP over http:// would crash; getRandomValues works everywhere.
 */
export function clientUuid(): string {
  if (typeof crypto.randomUUID === "function") return crypto.randomUUID();
  const b = crypto.getRandomValues(new Uint8Array(16));
  b[6] = (b[6] & 0x0f) | 0x40;
  b[8] = (b[8] & 0x3f) | 0x80;
  const h = Array.from(b, (x) => x.toString(16).padStart(2, "0")).join("");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-${h.slice(12, 16)}-${h.slice(16, 20)}-${h.slice(20)}`;
}
